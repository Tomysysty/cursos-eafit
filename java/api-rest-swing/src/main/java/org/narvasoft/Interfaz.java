    private void btnGetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGetActionPerformed
        String Id = idUser.getText();
        txtSalida.setText("");
        if (Id.isEmpty()) {
            //Metodo para traer todos los usuarios.
            Server request = new Server("GET", "http://localhost:8080/api/users", "Content-Type: application/json", "");
            txtSalida.append(request.response);
        } else {
            //Metodo para obtener un usuario por id
            Server request = new Server("GET", "http://localhost:8080/api/users", "Content-Type: application/json", "", Integer.parseInt(Id));
            txtSalida.append(request.response);
            idUser.setText("");            
        }
    }//GEN-LAST:event_btnGetActionPerformed

    private void btnPostActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPostActionPerformed
        String Name= NameUser.getText();
        String Email= EmailUser.getText();
        String Phone= PhoneUser.getText();
        String Body = Name + ',' + Email + ',' + Phone;
        Server request = new Server("POST", "http://localhost:8080/api/users", "Content-Type: application/json", Body);
        txtSalida.append(request.response);     
    }//GEN-LAST:event_btnPostActionPerformed

